import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  SCAFFOLD_HEADINGS, SCAFFOLD_LINES, applyPlan, hasHostContent, listSections, render, tokenOf,
  violations, AdoptError,
} from '../../scripts/adopt-claude-md.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const SCRIPT = join(ROOT, 'scripts/adopt-claude-md.mjs');
const TEMPLATE = readFileSync(join(ROOT, 'project-template/CLAUDE.md'), 'utf8');
const START = '<!-- cc:managed:start -->';
const END = '<!-- cc:managed:end -->';
const BLOCK = `${START}\n## Agent Identity\nManaged text.\n\n## Hard Constraints\n- Never.\n${END}\n`;
const withBlock = (host) => `${host}\n${BLOCK}`;

let dir;
let file;
beforeEach(() => { dir = mkdtempSync(join(tmpdir(), 'cc-adopt-')); file = join(dir, 'CLAUDE.md'); });
afterEach(() => { rmSync(dir, { recursive: true, force: true }); });

const sectionId = (text, heading, nth = 0) => listSections(text).filter((s) => s.heading === heading)[nth].id;

describe('trigger (AC6: scaffold never triggers)', () => {
  it('scaffold parity: the shipped template has exactly the scaffold headings and lines', () => {
    const outside = TEMPLATE.split(START)[0].split('\n').map((l) => l.trim());
    const headings = outside.filter((l) => l.startsWith('## ')).map((l) => l.slice(3));
    expect(headings).toEqual(SCAFFOLD_HEADINGS);
    const known = outside.filter((l) => l && !l.startsWith('## ') && !/^- \w+:/.test(l));
    for (const line of known) expect(SCAFFOLD_LINES.has(line)).toBe(true);
    expect(SCAFFOLD_LINES.size).toBe(known.filter((l, i) => known.indexOf(l) === i).length);
  });

  it('does not trigger on the shipped template', () => {
    expect(hasHostContent(TEMPLATE)).toBe(false);
  });

  it('does not trigger on a scaffold with filled fields and generated profiles', () => {
    const filled = TEMPLATE.replace('- Name:', '- Name: acme').replace(
      '<!-- cc-stack:managed: regenerated by /cc-stack, manual edits inside are overwritten -->',
      '<!-- cc-stack:managed: regenerated by /cc-stack, manual edits inside are overwritten -->\n- TypeScript: strict mode',
    );
    expect(hasHostContent(filled)).toBe(false);
  });

  it('triggers on host prose under a scaffold heading', () => {
    expect(hasHostContent(TEMPLATE.replace('## Conventions\n', '## Conventions\nUse tabs.\n'))).toBe(true);
  });

  it('triggers on a sentinel-less host and on host text around a block', () => {
    expect(hasHostContent('# Acme\n\n## Notes\nhi\n')).toBe(true);
    expect(hasHostContent(`before\n${BLOCK}after\n`)).toBe(true);
  });
});

describe('render', () => {
  const host = '# Acme\n\n## Commands\n- make\n\n## Notes\nkeep me\n\n## Conventions\nTabs.\n';

  it('is deterministic and moves mapped sections into slot order', () => {
    const text = withBlock(host);
    const plan = { [sectionId(text, 'Commands')]: 'commands', [sectionId(text, 'Conventions')]: 'conventions' };
    const out = render(text, plan);
    expect(render(text, plan)).toBe(out);
    expect(out.indexOf('## Notes')).toBeLessThan(out.indexOf('## Commands'));
    expect(out.indexOf('## Commands')).toBeLessThan(out.indexOf('## Conventions'));
  });

  it('AC3: copies the managed block verbatim', () => {
    const text = withBlock(host);
    const out = render(text, { [sectionId(text, 'Commands')]: 'commands' });
    expect(out.slice(out.indexOf(START), out.indexOf(END) + END.length)).toBe(BLOCK.trimEnd());
    expect(violations(text, out)).toEqual([]);
  });

  it('AC2: an empty plan keeps every byte', () => {
    const text = withBlock(host);
    expect(render(text, {})).toBe(text);
  });

  it('keeps host text before and after an existing block', () => {
    const text = `## Pre\nbefore\n\n${BLOCK}\n## Post\nafter\n`;
    const out = render(text, { [sectionId(text, 'Post')]: 'architecture' });
    expect(out.indexOf('## Pre')).toBeLessThan(out.indexOf(START));
    expect(out.indexOf('## Post')).toBeLessThan(out.indexOf(START));
    expect(out).toContain('after');
    expect(violations(text, out)).toEqual([]);
  });

  it('preserves CRLF bytes', () => {
    const text = withBlock(host).replace(/\n/g, '\r\n');
    const out = render(text, { [sectionId(text, 'Commands')]: 'commands' });
    expect(out.replace(/\r\n/g, '')).not.toContain('\n');
    expect(out).toContain('## Commands\r\n- make\r\n');
    expect(violations(text, out)).toEqual([]);
  });

  it('never treats a heading inside a fence as a section', () => {
    const text = withBlock('## Notes\n```\n## Fake\n```\n');
    const headings = listSections(text).map((s) => s.heading);
    expect(headings).toContain('Notes');
    expect(headings).not.toContain('Fake');
  });

  it('numbers duplicate headings separately and flags them', () => {
    const text = withBlock('## Conventions\nA\n\n## Conventions\nB\n\n## Agent Identity\nmine\n');
    const secs = listSections(text);
    expect(secs.filter((s) => s.duplicateInFile).length).toBe(2);
    expect(secs.find((s) => s.heading === 'Agent Identity').duplicateOfManagedBlock).toBe(true);
    const out = render(text, { [sectionId(text, 'Conventions', 1)]: 'conventions' });
    expect(out).toContain('A\n');
    expect(out).toContain('B\n');
  });

  it('rejects an unknown slot or section id', () => {
    const text = withBlock(host);
    expect(() => render(text, { 1: 'nonsense' })).toThrow(AdoptError);
    expect(() => render(text, { 99: 'commands' })).toThrow(AdoptError);
  });
});

describe('refusals', () => {
  it('refuses unbalanced sentinels', () => {
    expect(() => hasHostContent(`x\n${START}\nnever closed\n`)).toThrow(/unbalanced/);
    expect(() => render(`${END}\n${START}\n`, {})).toThrow(AdoptError);
  });

  it('refuses an open fence', () => {
    expect(() => listSections('## A\n```\nunclosed\n')).toThrow(/fence/);
  });
});

describe('apply (AC1, AC4, AC5)', () => {
  const host = '# Acme\n\n## Commands\n- make\n\n## Notes\nkeep\n';
  const plan = { 1: 'commands' };

  it('AC1: refuses a token that is not the sha256 of the exact render', () => {
    writeFileSync(file, withBlock(host));
    expect(() => applyPlan(file, plan, 'deadbeef')).toThrow(/token/);
    expect(() => applyPlan(file, plan, tokenOf(render(withBlock(host), {})))).toThrow(/token/);
    expect(readFileSync(file, 'utf8')).toBe(withBlock(host));
    expect(readdirSync(dir)).toEqual(['CLAUDE.md']);
  });

  it('AC4: backs up the original before writing and returns the path', () => {
    const original = withBlock(host);
    writeFileSync(file, original);
    const backup = applyPlan(file, plan, tokenOf(render(original, plan)));
    expect(backup).toMatch(/CLAUDE\.md\.installer-backup\.\d{8}T\d{6}Z$/);
    expect(readFileSync(backup, 'utf8')).toBe(original);
    expect(readFileSync(file, 'utf8')).toBe(render(original, plan));
  });

  it('AC5: the CLI has no write path except apply, and a declined flow is a no-op', () => {
    writeFileSync(file, withBlock(host));
    writeFileSync(join(dir, 'plan.json'), JSON.stringify(plan));
    for (const args of [['sections', file], ['render', file, join(dir, 'plan.json')]]) {
      expect(spawnSync('node', [SCRIPT, ...args], { encoding: 'utf8' }).status).toBe(0);
    }
    expect(readFileSync(file, 'utf8')).toBe(withBlock(host));
    expect(readdirSync(dir).sort()).toEqual(['CLAUDE.md', 'plan.json']);
  });

  it('CLI: sections reports trigger false on scaffold, apply with the shown token writes', () => {
    writeFileSync(file, TEMPLATE);
    const scaffold = spawnSync('node', [SCRIPT, 'sections', file], { encoding: 'utf8' });
    expect(JSON.parse(scaffold.stdout)).toEqual({ trigger: false });
    writeFileSync(file, withBlock(host));
    writeFileSync(join(dir, 'plan.json'), JSON.stringify(plan));
    const shown = spawnSync('node', [SCRIPT, 'render', file, join(dir, 'plan.json')], { encoding: 'utf8' });
    const token = shown.stderr.trim().split(': ')[1];
    const done = spawnSync('node', [SCRIPT, 'apply', file, join(dir, 'plan.json'), token], { encoding: 'utf8' });
    expect(done.stdout).toMatch(/^backup: .*installer-backup/);
    expect(readFileSync(file, 'utf8')).toBe(shown.stdout);
  });
});

describe('independent black-box regressions (FEAT-040 test pass)', () => {
  const plan = (text) => ({ [sectionId(text, 'Team Rules')]: 'conventions' });

  it('refuses a stale token when the file changes between render and apply, leaving it untouched', () => {
    const text = '## Team Rules\nr\n## Conventions\nc\n';
    writeFileSync(file, text);
    const token = tokenOf(render(text, plan(text)));
    writeFileSync(file, `${text}## Late\nz\n`);
    expect(() => applyPlan(file, plan(text), token)).toThrow(AdoptError);
    expect(readFileSync(file, 'utf8')).toBe(`${text}## Late\nz\n`);
  });

  it('keeps a BOM, CRLF, unicode and a missing trailing newline byte for byte on an empty plan', () => {
    const text = '﻿# Título\r\n## Reglas 日本語 \u{1F600}\r\ntexto\r\n## Fin\r\nsin salto';
    writeFileSync(file, text);
    expect(render(text, {})).toBe(text);
  });

  // Two applies within one second share a timestamp; the second must take a new name.
  it('a second apply in the same second does not clobber the first backup', () => {
    const text = '## Team Rules\nr\n## Conventions\nc\n';
    writeFileSync(file, text);
    const first = applyPlan(file, plan(text), tokenOf(render(text, plan(text))));
    const current = readFileSync(file, 'utf8');
    const second = applyPlan(file, {}, tokenOf(render(current, {})));
    expect(second).not.toBe(first);
    expect(readFileSync(first, 'utf8')).toBe(text);
  });
});

describe('round 2 fixes', () => {
  const PROFILES_MARK = 'overwritten -->';
  const hostProfiles = (extra) => TEMPLATE.split(START)[0].replace(PROFILES_MARK, `${PROFILES_MARK}\n${extra}`);

  it('host prose under Active Stack Profiles triggers; generated bullets and subsections do not', () => {
    expect(hasHostContent(hostProfiles('### TypeScript\n- Use strict mode.'))).toBe(false);
    expect(hasHostContent(hostProfiles('Our own profile notes.'))).toBe(true);
  });

  it('lists a host-edited Active Stack Profiles section so it can be kept or moved', () => {
    const text = withBlock(hostProfiles('Our notes.'));
    const id = sectionId(text, 'Active Stack Profiles');
    expect(render(text, { [id]: 'keep' })).toBe(text);
    expect(violations(text, render(text, { [id]: 'architecture' }))).toEqual([]);
  });

  it('a third apply in the same second keeps every earlier backup', () => {
    writeFileSync(file, '## A\n1\n\n## Conventions\nc\n');
    const backups = new Set();
    for (let i = 0; i < 3; i++) {
      const current = readFileSync(file, 'utf8');
      const plan = i === 0 ? { 1: 'conventions' } : {};
      backups.add(applyPlan(file, plan, tokenOf(render(current, plan))));
    }
    expect(backups.size).toBe(3);
  });

  it('a failed backup aborts the write', () => {
    const text = withBlock('## A\n1\n');
    writeFileSync(file, text);
    const absent = join(dir, 'nope', 'CLAUDE.md');
    expect(() => applyPlan(absent, {}, tokenOf(render(text, {})))).toThrow(AdoptError);
    expect(readFileSync(file, 'utf8')).toBe(text);
  });

  it('violations catches a duplicated section that substring matching would miss', () => {
    const original = withBlock('## A\nx\n\n## B\ny\n');
    const duplicated = original.replace('## B\ny\n', '## B\ny\n\n## B\ny\n');
    expect(violations(original, duplicated)).toContain('host sections lost, duplicated or altered');
    expect(violations(original, original)).toEqual([]);
  });

  it('rejects a slot for the preamble but allows keep', () => {
    const text = withBlock('# Title\n\n## A\nx\n');
    expect(() => render(text, { 0: 'identity' })).toThrow(/cannot be moved/);
    expect(render(text, { 0: 'keep' })).toBe(text);
  });

  it('turns missing or invalid plan files into exit 2 with no stack trace', () => {
    writeFileSync(file, withBlock('## A\nx\n'));
    writeFileSync(join(dir, 'bad.json'), '{nope');
    writeFileSync(join(dir, 'arr.json'), '[]');
    for (const planPath of ['missing.json', 'bad.json', 'arr.json']) {
      const run = spawnSync('node', [SCRIPT, 'render', file, join(dir, planPath)], { encoding: 'utf8' });
      expect(run.status).toBe(2);
      expect(run.stderr).toMatch(/^ERROR: /);
      expect(run.stderr).not.toMatch(/\n\s+at /);
    }
  });
});
