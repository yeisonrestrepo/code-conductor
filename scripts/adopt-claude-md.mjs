#!/usr/bin/env node
// scripts/adopt-claude-md.mjs (FEAT-040)
// Semantic adoption of a host CLAUDE.md, split so no judgment can change bytes:
// the model only classifies each host section into a slot; this script renders the
// resulting file deterministically and writes it only when handed the sha256 of the
// exact render the owner was shown.
//
// usage:
//   adopt-claude-md.mjs sections <file>                    -> JSON for the model
//   adopt-claude-md.mjs render   <file> <plan.json>        -> resulting file on stdout, token on stderr
//   adopt-claude-md.mjs apply    <file> <plan.json> <token> -> backup, then write
// plan.json maps a section id to a slot, e.g. {"0":"conventions","2":"keep"}.

import fs from 'node:fs';
import crypto from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { scanLines, SENTINEL_START, SENTINEL_END } from '../lib/installer/merge-md.mjs';

// Scaffold order of project-template/CLAUDE.md; a moved section lands in this order.
export const SLOTS = ['identity', 'commands', 'architecture', 'conventions', 'out-of-scope', 'keep'];
const KEEP = SLOTS.indexOf('keep');

// Parity-tested against project-template/CLAUDE.md. A line outside the managed block
// that is not one of these (or a field line) is host content.
export const SCAFFOLD_HEADINGS = [
  'Project Identity', 'Development Commands', 'Architecture Notes',
  'Conventions', 'Out of Scope', 'Active Stack Profiles',
];
export const SCAFFOLD_LINES = new Set([
  '# Project Claude Configuration',
  'Extends global CLAUDE.md. Project-specific rules take precedence over global ones.',
  '<!-- Key architectural decisions for this project -->',
  '<!-- Project-specific conventions that override global defaults -->',
  '<!-- Things Claude should not touch in this project -->',
  '<!-- cc-stack:managed: regenerated by /cc-stack, manual edits inside are overwritten -->',
  '---',
]);
// Filled-in fields are conductor's own writes (/cc-stack, /cc-init), not host prose.
const FIELD_LINE = /^- (Name|Description|Stack|Language|Build|Test|Lint|Format|Setup|Specs|Plans):/;
const GENERATED_SECTION = 'Active Stack Profiles';
// /cc-stack 5b writes only `### stack` subsections and `- ` bullets there (prose is
// disallowed), so any other line in that section is the host's own.
const GENERATED_LINE = /^(- |### )/;

export class AdoptError extends Error {}

// Exact-byte pieces: lines keep their CR, so rejoining on '\n' reproduces the file.
export function splitManaged(text) {
  const scan = scanLines(text);
  if (scan.status === 'unbalanced') throw new AdoptError('unbalanced managed-block sentinels');
  if (scan.openFence) throw new AdoptError('unclosed code fence');
  if (scan.status === 'none') return { before: scan.lines, block: [], after: [] };
  return {
    before: scan.lines.slice(0, scan.start),
    block: scan.lines.slice(scan.start, scan.end + 1),
    after: scan.lines.slice(scan.end + 1),
  };
}

// A preamble (heading null) plus one segment per fence-aware `## ` heading.
export function sectionsOf(lines) {
  const cuts = scanLines(lines.join('\n')).headings.map((h) => h.index);
  const bounds = [...new Set([0, ...cuts, lines.length])];
  const out = [];
  for (let i = 0; i < bounds.length - 1; i++) {
    const segment = lines.slice(bounds[i], bounds[i + 1]);
    const heading = segment[0].startsWith('## ') ? segment[0].replace(/\r$/, '').slice(3).trim() : null;
    out.push({ heading, lines: segment });
  }
  return out;
}

// Scaffold-only files never trigger: the owner gets nothing to adopt.
export function hasHostContent(text) {
  const parts = splitManaged(text);
  let generated = false;
  for (const raw of [...parts.before, ...parts.after]) {
    const line = raw.replace(/\r$/, '').trim();
    if (line.startsWith('## ')) generated = line.slice(3).trim() === GENERATED_SECTION;
    const scaffold = line === '' || SCAFFOLD_LINES.has(line) || FIELD_LINE.test(line)
      || SCAFFOLD_HEADINGS.some((h) => line === `## ${h}`)
      || (generated && GENERATED_LINE.test(line));
    if (!scaffold) return true;
  }
  return false;
}

// Host sections in file order, each tagged with its side of the block and whether its
// heading collides with another host section or the managed block.
export function listSections(text) {
  const parts = splitManaged(text);
  const blockHeadings = new Set(sectionsOf(parts.block).map((s) => s.heading));
  const all = [
    ...sectionsOf(parts.before).map((s) => ({ ...s, where: 'before' })),
    ...sectionsOf(parts.after).map((s) => ({ ...s, where: 'after' })),
  ];
  const seen = new Map();
  all.forEach((s, id) => { s.id = id; seen.set(s.heading, (seen.get(s.heading) ?? 0) + 1); });
  return all.map((s) => ({
    ...s,
    duplicateInFile: s.heading !== null && seen.get(s.heading) > 1,
    duplicateOfManagedBlock: s.heading !== null && blockHeadings.has(s.heading),
  }));
}

function slotRank(plan, id) {
  const slot = plan[id] ?? 'keep';
  if (!SLOTS.includes(slot)) throw new AdoptError(`unknown slot "${slot}" for section ${id}`);
  return SLOTS.indexOf(slot);
}

// The preamble anchors the file's title and intro; a slot for it is a mistake to surface.
function checkPlan(plan, sections) {
  for (const id of Object.keys(plan)) {
    const section = sections.find((s) => String(s.id) === id);
    if (!section) throw new AdoptError(`plan names unknown section ${id}`);
    if (section.heading === null && plan[id] !== 'keep') throw new AdoptError(`section ${id} has no heading and cannot be moved`);
  }
}

// Pure function of (text, plan): same input, same bytes, so a hash is a sound approval
// token. The preamble never moves and the block is copied verbatim.
export function render(text, plan) {
  const parts = splitManaged(text);
  const sections = listSections(text);
  checkPlan(plan, sections);
  const moved = sections
    .filter((s) => s.heading !== null && slotRank(plan, s.id) !== KEEP)
    .sort((a, b) => slotRank(plan, a.id) - slotRank(plan, b.id) || a.id - b.id);
  const stays = sections.filter((s) => !moved.includes(s));
  const before = [...stays.filter((s) => s.where === 'before'), ...moved].flatMap((s) => s.lines);
  const after = stays.filter((s) => s.where === 'after').flatMap((s) => s.lines);
  return [before, parts.block, after].filter((a) => a.length).map((a) => a.join('\n')).join('\n');
}

export const tokenOf = (rendered) => crypto.createHash('sha256').update(rendered).digest('hex');

// Acceptance criteria 2 and 3 as an independent check on the render, not on the plan.
// Host sections must survive as the same multiset, so a lost, duplicated or altered
// section is caught; substring matching would miss a duplicate. The preamble must
// still lead the file. Slot moves reorder sections by design, so order is otherwise free.
export function violations(original, rendered) {
  const o = splitManaged(original);
  const r = splitManaged(rendered);
  const found = [];
  if (o.block.join('\n') !== r.block.join('\n')) found.push('managed block changed');
  const bytesOf = (parts) => [...sectionsOf(parts.before), ...sectionsOf(parts.after)].map((s) => s.lines.join('\n'));
  const expected = bytesOf(o).sort();
  const actual = bytesOf(r).sort();
  if (expected.length !== actual.length || expected.some((s, i) => s !== actual[i])) found.push('host sections lost, duplicated or altered');
  const lead = (parts) => sectionsOf(parts.before)[0];
  if (lead(o)?.heading === null && lead(o).lines.join('\n') !== lead(r)?.lines.join('\n')) found.push('leading preamble moved');
  return found;
}

// Same name shape as the installer's backup so one prune/restore story covers both.
export function backupPath(file, now = new Date()) {
  const stamp = now.toISOString().replace(/[-:]/g, '').replace(/\.\d+Z$/, 'Z');
  return `${file}.installer-backup.${stamp}`;
}

export function applyPlan(file, plan, approvedToken) {
  const text = readText(file, 'file');
  const rendered = render(text, plan);
  if (approvedToken !== tokenOf(rendered)) throw new AdoptError('token does not match the shown result; nothing written');
  const bad = violations(text, rendered);
  if (bad.length) throw new AdoptError(`refused: ${bad.join('; ')}`);
  const backup = copyToFreshBackup(file);
  fs.writeFileSync(file, rendered);
  return backup;
}

const MAX_BACKUP_ATTEMPTS = 100;

// EXCL so a second apply in the same second can never overwrite the first backup, the
// only copy of the original. Any other failure aborts before the file is touched.
function copyToFreshBackup(file) {
  const base = backupPath(file);
  for (let n = 0; n < MAX_BACKUP_ATTEMPTS; n++) {
    const candidate = n === 0 ? base : `${base}.${n}`;
    try {
      fs.copyFileSync(file, candidate, fs.constants.COPYFILE_EXCL);
      return candidate;
    } catch (err) {
      if (err.code !== 'EEXIST') throw new AdoptError(`backup failed (${err.code ?? err.message}); nothing written`);
    }
  }
  throw new AdoptError('backup failed (no free backup name); nothing written');
}

function describeSections(text) {
  if (!hasHostContent(text)) return { trigger: false };
  const sections = listSections(text).map(({ lines, ...rest }) => ({ ...rest, preview: lines.join('\n').slice(0, 80) }));
  return { trigger: true, slots: SLOTS, sections };
}

function readText(path, what) {
  if (!path) throw new AdoptError(`missing ${what} argument`);
  try { return fs.readFileSync(path, 'utf8'); } catch (err) { throw new AdoptError(`cannot read ${what} ${path}: ${err.code ?? err.message}`); }
}

function readPlan(planFile) {
  let plan;
  try { plan = JSON.parse(readText(planFile, 'plan')); } catch (err) {
    if (err instanceof AdoptError) throw err;
    throw new AdoptError(`plan ${planFile} is not valid JSON`);
  }
  if (plan === null || typeof plan !== 'object' || Array.isArray(plan)) throw new AdoptError('plan must be a JSON object of section id to slot');
  return plan;
}

function main([command, file, planFile, token]) {
  if (command === 'sections') return console.log(JSON.stringify(describeSections(readText(file, 'file')), null, 1));
  if (command === 'render') {
    const rendered = render(readText(file, 'file'), readPlan(planFile));
    process.stdout.write(rendered);
    return console.error(`approval token: ${tokenOf(rendered)}`);
  }
  if (command === 'apply') return console.log(`backup: ${applyPlan(file, readPlan(planFile), token)}`);
  throw new AdoptError('usage: adopt-claude-md.mjs sections|render|apply <file> [plan.json] [token]');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  try { main(process.argv.slice(2)); } catch (err) {
    if (!(err instanceof AdoptError)) throw err;
    console.error(`ERROR: ${err.message}`);
    process.exit(2);
  }
}
